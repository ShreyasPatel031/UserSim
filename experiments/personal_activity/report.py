"""Markdown report for one run."""

from __future__ import annotations

import math
from typing import Any

from .evaluate import HIGHER_IS_BETTER, KEY_METRICS

SWITCH_COLS = [
    ("next_top1", "next top-1 ↑"),
    ("next_top3", "next top-3 ↑"),
    ("dwell_mae_s", "dwell MAE s ↓"),
    ("dwell_log_mae", "dwell log-MAE ↓"),
    ("idle_brier", "idle Brier ↓"),
    ("idle_auc", "idle AUC ↑"),
]
DAY_COLS = [
    ("first_active_mae", "first-active MAE min ↓"),
    ("active_mae", "active-time MAE min ↓"),
    ("share_tv", "share TV ↓"),
    ("call_brier", "call Brier ↓"),
    ("call_auc", "call AUC ↑"),
    ("calls_per_day_err", "call slots/day err ↓"),
]

LABELS = {
    "most_frequent": "most-frequent",
    "last_value": "last-value (repeat)",
    "markov1": "Markov (1st order)",
    "time_of_day": "time-of-day prior",
    "simulator": "**simulator (classical)**",
    "llm": "**simulator (LLM)**",
}
DAY_LABELS = {
    "most_frequent": "most-frequent (median day)",
    "last_value": "last-value (yesterday)",
    "time_of_day": "time-of-day / day-type prior",
    "simulator": "**simulator (rollouts + call model)**",
    "llm": "**simulator (LLM)**",
}


def _f(v: Any, nd: int = 3) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "–"
    if isinstance(v, float):
        if abs(v) >= 100:
            return f"{v:.0f}"
        return f"{v:.{nd}f}"
    return str(v)


def _table(metrics: dict, models: list[str], cols, labels) -> list[str]:
    best: dict[str, float] = {}
    for k, _ in cols:
        vals = [metrics.get(m, {}).get(k) for m in models]
        vals = [v for v in vals if isinstance(v, float) and not math.isnan(v)]
        if vals:
            best[k] = max(vals) if k in HIGHER_IS_BETTER or k.endswith("auc") else min(vals)
    out = ["| model | " + " | ".join(h for _, h in cols) + " |", "|---" * (len(cols) + 1) + "|"]
    for m in models:
        row = [labels.get(m, m)]
        for k, _ in cols:
            v = metrics.get(m, {}).get(k)
            s = _f(v)
            if k in best and isinstance(v, float) and v == best[k]:
                s = f"**{s}**"
            row.append(s)
        out.append("| " + " | ".join(row) + " |")
    return out


def _compare_table(cmp: dict) -> list[str]:
    out = [
        "| metric | task | simulator | best baseline | baseline value | loss diff (90% CI) | verdict |",
        "|---|---|---|---|---|---|---|",
    ]
    for k, c in cmp.items():
        task, _desc = KEY_METRICS[k]
        lo, hi = c["ci90"]
        out.append(
            f"| {k} | {task} | {_f(c['challenger'])} | {LABELS.get(c['best_baseline'], c['best_baseline']).strip('*')} | "
            f"{_f(c['baseline'])} | {_f(c['loss_diff'])} ({_f(lo)}, {_f(hi)}) | {c['verdict']} |"
        )
    return out


def render(res: dict, meta: dict) -> str:
    L: list[str] = []
    L.append(f"# Personal activity simulator — {meta.get('title', 'run')}")
    L.append("")
    if meta.get("synthetic"):
        L.append("> **Synthetic data.** Generated by `synth.py`; numbers say the pipeline works, not how well it "
                 "predicts a real person.")
        L.append("")
    d = meta["data"]
    L.append("## Data and split")
    L.append("")
    L.append(
        f"- {d['days']} observed days, {d['segments']} focused segments, {d['idle_gaps']} idle gaps, "
        f"{d['call_episodes']} call episodes; {d['lines']} lines read, {d['duplicate_lines']} duplicates "
        f"(weekly overlap) dropped, {d['bad_lines']} unparseable."
    )
    L.append(
        f"- Time-ordered split: train {meta['train_range']} ({meta['n_train']} days, of which the last "
        f"{meta['n_val']} tune blend weights), test {meta['test_range']} ({meta['n_test']} days)."
    )
    L.append(f"- Context vocabulary: {meta['n_vocab']} labels from train (rest → `other`). Timezone {meta['tz']}.")
    L.append(f"- Test points: {res['n_test_switch_points']} switches ({res['n_test_next_points']} with a next context in the same session).")
    L.append("")

    L.append("## Scorecard: does the simulator predict key behaviour?")
    L.append("")
    cmp = res["simulator_vs_baselines"]
    wins = sum(1 for c in cmp.values() if c["verdict"].startswith("better (CI"))
    any_w = sum(1 for c in cmp.values() if c["verdict"].startswith("better"))
    L.append(
        f"Classical simulator vs the **best** baseline for each metric (picked on the test set, which favours "
        f"the baselines): better on **{any_w}/{len(cmp)}** key metrics, with the 90% day-clustered bootstrap CI "
        f"excluding zero on **{wins}/{len(cmp)}**."
    )
    L.append("")
    L += _compare_table(cmp)
    L.append("")
    if "llm_days_vs_baselines" in res:
        L.append("LLM simulator (day-level tasks) vs best baseline:")
        L.append("")
        L += _compare_table(res["llm_days_vs_baselines"])
        L.append("")

    L.append("## Switch-level tasks (fit on train days, all test switches)")
    L.append("")
    L += _table(res["metrics"], res["switch_models"], SWITCH_COLS, LABELS)
    L.append("")
    w = res.get("simulator_mixture_weights") or {}
    L.append("Simulator next-context mixture weights (tuned on validation days): "
             + ", ".join(f"{k} {v:.1f}" for k, v in w.items()))
    L.append("")

    if "llm" in res:
        lm = res["llm"]
        L.append("## LLM simulator")
        L.append("")
        L.append(
            f"Mode `{lm['mode']}`; estimated cost ${lm['estimated_cost_usd']:.3f}, spent ${lm['spent_usd']:.3f} "
            f"over {lm['calls']} calls ({lm['skipped_for_budget']} skipped for budget). "
            f"{lm['answered_points']}/{lm['sampled_points']} sampled switch points answered, "
            f"{lm['answered_days']} days answered."
        )
        if lm.get("errors"):
            L.append(f"Errors: {lm['errors']}")
        L.append("")
        if "llm_subset" in res:
            sub = res["llm_subset"]
            L.append(f"Same {sub['n_points']} sampled switch points for every model:")
            L.append("")
            L += _table(sub["metrics"], res["switch_models"] + ["llm"], SWITCH_COLS, LABELS)
            L.append("")
            L.append("LLM vs best baseline on that subset:")
            L.append("")
            L += _compare_table(sub["vs_baselines"])
            L.append("")

    L.append("## Day-level tasks (day-ahead: each test day uses all earlier days)")
    L.append("")
    L += _table(res["metrics"], res["day_models"], DAY_COLS, DAY_LABELS)
    L.append("")
    sm = res["metrics"].get("simulator", {})
    if "first_active_80pct_coverage" in sm:
        L.append(
            f"Simulator 80% intervals from rollouts cover the actual first-active time on "
            f"{sm['first_active_80pct_coverage']:.0%} and the actual active time on "
            f"{sm['active_80pct_coverage']:.0%} of test days (well calibrated ≈ 80%)."
        )
        L.append("")

    L.append("## Metric definitions")
    L.append("")
    for k, (task, desc) in KEY_METRICS.items():
        L.append(f"- `{k}` ({task}): {desc}.")
    L.append("- `idle_auc`, `call_auc`: ranking quality of the probabilities (0.5 = chance).")
    L.append("- `calls_per_day_err`: |expected call slots − actual call slots| per day.")
    L.append("- Loss diff < 0 means the simulator has lower loss than the best baseline; for accuracies the loss is 1 − accuracy.")
    L.append("")
    return "\n".join(L)
